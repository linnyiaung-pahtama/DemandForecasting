"""PostgreSQL connection and schema.

The tables mirror the SQLite layout the tool used up to version 8, column for column and in the same storage
types (text, integer, double precision), so data copied from an old orderplan.db is identical: plans stay JSON
text byte for byte and dates stay ISO text. The unused v5/v7 columns (holding_months, order_cycle_months) are kept,
so old change-log lines still make sense. Later schema changes: add them to SCHEMA as
ALTER TABLE ... ADD COLUMN IF NOT EXISTS.
"""
import psycopg
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row

from app import config

SCHEMA_VERSION = 8  # the SQLite layout mirrored here; copy_from_sqlite only accepts files at this version

SCHEMA = """
CREATE TABLE IF NOT EXISTS supplier_settings (
    supplier text PRIMARY KEY,
    holding_months double precision NULL,
    updated_at text NOT NULL,
    moq double precision NOT NULL DEFAULT 0,
    lead_time_days integer NULL,
    order_cycle_months integer NOT NULL DEFAULT 1,
    order_cycle_weeks integer NOT NULL DEFAULT 4,
    holding_days double precision NULL
);
CREATE TABLE IF NOT EXISTS settings_log (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier text NOT NULL,
    old_value double precision NULL,
    new_value double precision NULL,
    changed_at text NOT NULL,
    field text NOT NULL DEFAULT 'holding_months'
);
CREATE TABLE IF NOT EXISTS runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at text NOT NULL,
    file_name text NOT NULL,
    sales_file_name text NOT NULL,
    plan_date text NOT NULL,
    sku_count integer NOT NULL,
    parsed_json text NOT NULL,
    actual_json text NOT NULL,
    result_json text NOT NULL,
    pg_file_name text NULL,
    pdg_file_name text NULL,
    stock_json text NULL,
    sit_file_name text NULL
);
"""


def connect(database_url: str | None = None, schema: str | None = None) -> psycopg.Connection:
    """A connection whose rows are dicts. As a context manager it commits on success, rolls back on an error, and
    closes. `schema` (tests only) puts the tables in that schema instead of public."""
    url = database_url or config.DATABASE_URL
    kwargs: dict = {}
    if config.DATABASE_USER and not conninfo_to_dict(url).get("user"):
        kwargs.update(user=config.DATABASE_USER, password=config.DATABASE_PASSWORD)
    if schema:
        kwargs["options"] = f"-c search_path={schema}"
    return psycopg.connect(url, row_factory=dict_row, **kwargs)


def init_schema(conn: psycopg.Connection) -> None:
    conn.execute(SCHEMA)
